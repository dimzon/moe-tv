package tv.own.owntv.core.sync

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * `play/options` → [RutubeParser.parsePlayOptions] for the live path, with a focus on the
 * `captions[]` sidecar list (RuTube linear-TV subtitles): it rides beside the stream URL as plain
 * references (`srt`/`vtt` files the client side-loads), so the parser must carry it without ever
 * letting one odd entry cost the stream — and must treat "no captions" as a normal, empty answer.
 * Kept pure-JVM like the rest of the parser tests.
 */
class RutubeParserPlayOptionsTest {

    @Test
    fun `ready carries advertised captions beside the stream`() {
        val result = RutubeParser.parsePlayOptions(
            200,
            """{"live_streams":{"hls":[{"url":"https://example.test/live.m3u8"}]},
                "captions":[
                  {"sub_id":7,"format":"vtt","langTitle":"Russian",
                   "file":"https://pic.rtbcdn.ru/7.vtt","is_autogenerated":true},
                  {"sub_id":8,"format":"srt","file":"https://pic.rtbcdn.ru/8.srt"}
                ]}""",
        )
        assertTrue("the HLS url wins", result is RutubePlayback.Ready)
        val ready = result as RutubePlayback.Ready
        assertEquals("https://example.test/live.m3u8", ready.url)
        assertEquals(
            listOf(
                RutubeCaption(7, "vtt", "https://pic.rtbcdn.ru/7.vtt", "Russian", true),
                RutubeCaption(8, "srt", "https://pic.rtbcdn.ru/8.srt"),
            ),
            ready.captions,
        )
    }

    @Test
    fun `a feed advertising nothing yields an empty caption list`() {
        val ready = RutubeParser.parsePlayOptions(
            200,
            """{"live_streams":{"hls":[{"url":"https://example.test/live.m3u8"}]}}""",
        ) as RutubePlayback.Ready
        assertEquals(emptyList<RutubeCaption>(), ready.captions)

        // the field can be present and still empty — that is a normal answer, not an error
        val empty = RutubeParser.parsePlayOptions(
            200,
            """{"live_streams":{"hls":[{"url":"https://example.test/live.m3u8"}]},"captions":[]}""",
        ) as RutubePlayback.Ready
        assertEquals(emptyList<RutubeCaption>(), empty.captions)
    }

    @Test
    fun `unparseable caption entries are skipped without costing the stream`() {
        val ready = RutubeParser.parsePlayOptions(
            200,
            """{"live_streams":{"hls":[{"url":"https://example.test/live.m3u8"}]},
                "captions":[
                  "not-an-object",
                  {"sub_id":1,"format":"txt","file":"https://pic.rtbcdn.ru/1.txt"},
                  {"sub_id":2,"format":"SRT","file":"https://pic.rtbcdn.ru/2.srt"},
                  {"sub_id":3,"format":"vtt"},
                  {"format":"vtt","file":"https://pic.rtbcdn.ru/4.vtt"},
                  {"sub_id":5,"format":"vtt","file":"https://pic.rtbcdn.ru/5.vtt","langTitle":"English"}
                ]}""",
        ) as RutubePlayback.Ready
        assertEquals("https://example.test/live.m3u8", ready.url)
        // entries 3 and 4 above are the odd ones out: no file URL, and no sub_id (its index, 4, stands in)
        assertEquals(
            listOf(
                RutubeCaption(2, "srt", "https://pic.rtbcdn.ru/2.srt"),
                RutubeCaption(4, "vtt", "https://pic.rtbcdn.ru/4.vtt"),
                RutubeCaption(5, "vtt", "https://pic.rtbcdn.ru/5.vtt", "English"),
            ),
            ready.captions,
        )
    }

    @Test
    fun `non-ready answers stay answers`() {
        val result = RutubeParser.parsePlayOptions(
            200,
            """{"detail":{"type":"common_subscription","name":"Premier"}}""",
        )
        assertEquals(RutubePlayback.Unavailable(UnavailableReason.LOGIN_REQUIRED, "Premier"), result)
    }

    @Test
    fun `malformed body never throws`() {
        org.junit.Assert.assertTrue(RutubeParser.parsePlayOptions(200, null) is RutubePlayback.Unavailable)
        org.junit.Assert.assertTrue(RutubeParser.parsePlayOptions(200, "not json{") is RutubePlayback.Unavailable)
        // a JSON root that is not an object at all is the same unplayable as no body
        val result = RutubeParser.parsePlayOptions(200, "42")
        assertTrue(result is RutubePlayback.Unavailable)
    }

    @Test
    fun `vod balancer urls are ready like live`() {
        val ready = RutubeParser.parsePlayOptions(
            200,
            """{"video_balancer":{"m3u8":"https://example.test/vod.m3u8"}}""",
        ) as RutubePlayback.Ready
        assertEquals("https://example.test/vod.m3u8", ready.url)
        assertEquals(emptyList<RutubeCaption>(), ready.captions)
    }
}
