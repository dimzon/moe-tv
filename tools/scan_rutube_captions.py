#!/usr/bin/env python3
"""Rescan RuTube live channels for play-options captions[] (subtitles).

Usage: python -I tools/scan_rutube_captions.py [--out scan_results.json]
Bypasses all proxies; uses the TV play-options params OWNTV uses (pver=v2, referer, no_404).
Mirrors SmartRuTube ExoMediaSourceFactory side-load chain; see docs/rutube-live-subtitles.md.
"""
import json
import os
import time
import urllib.request
import urllib.error

BASE = "https://rutube.ru"
UA = "com.rutube.mobile/31.18.0 (Android 13)"
# Force the proxy OFF, two ways: empty ProxyHandler (urllib-level) AND wiping
# every proxy env var (some stacks re-read them at connect time). The RuTube
# CDN WAF behaves differently behind a proxy (OWNTV docs use curl --noproxy '*').
for _k in ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "http_proxy", "https_proxy", "all_proxy"):
    os.environ.pop(_k, None)
os.environ["NO_PROXY"] = "*"
OPENER = urllib.request.build_opener(
    urllib.request.ProxyHandler({}),
    urllib.request.HTTPSHandler(),
)


def get(url, tries=3):
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={
                "User-Agent": UA,
                "Referer": "https://rutube.ru/",
                "Accept": "application/json",
            })
            with OPENER.open(req, timeout=20) as r:
                return json.loads(r.read().decode("utf-8", "replace"))
        except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError, OSError) as e:
            code = getattr(e, "code", None)
            if code in (429, 500, 502, 503) or code is None:
                time.sleep(1.5 * (i + 1))
                continue
            return {"__error__": str(e), "__code__": code}
        except Exception as e:  # noqa: BLE001 - json decode etc.
            return {"__error__": repr(e)}
    return {"__error__": "retries exhausted"}


def channels():
    out = []
    url = f"{BASE}/api/v2/video/stream/tvbroadcastinfo/?client=tv&tvprogramm=false"
    pages = 0
    while url and pages < 40:
        data = get(url)
        pages += 1
        results = data.get("results") or []
        for ch in results:
            vid = (ch.get("video_id") or ch.get("id") or "").strip("/")
            name = ch.get("title") or ch.get("name") or vid
            if vid:
                out.append((name, vid))
        url = data.get("next")
        time.sleep(0.2)
    return out


def main():
    chans = channels()
    print(f"channels: {len(chans)}", flush=True)
    with_subs, empty, errs = [], [], []
    for idx, (name, vid) in enumerate(chans, 1):
        opts = get(
            f"{BASE}/api/play/options/{vid}/?no_404=true&pver=v2"
            "&referer=https%3A%2F%2Ftv-androidtv.rutube.ru"
        )
        if "__error__" in opts:
            errs.append((name, vid, opts.get("__code__"), opts["__error__"]))
        else:
            caps = opts.get("captions") or []
            if caps:
                with_subs.append((name, vid, caps))
            else:
                empty.append((name, vid))
        if idx % 20 == 0:
            print(f"  {idx}/{len(chans)} ... subs so far: {len(with_subs)}", flush=True)
        time.sleep(0.25)

    print("\n===== RESULT =====")
    print(f"total: {len(chans)}  with captions: {len(with_subs)}  without: {len(empty)}  errors: {len(errs)}")
    for name, vid, caps in with_subs:
        langs = ", ".join(
            f"{c.get('langTitle') or c.get('code')}({c.get('format')}"
            f"{',auto' if c.get('is_autogenerated') else ''})"
            for c in caps
        )
        print(f"  [subs] {name}  id={vid}  -> {langs}")
    for name, vid, code, err in errs[:20]:
        print(f"  [err ] {name}  id={vid}  http={code}  {err[:100]}")
    with open("scan_results.json", "w", encoding="utf-8") as f:
        json.dump(
            {
                "with_captions": [
                    {"name": n, "id": v, "captions": c} for n, v, c in with_subs
                ],
                "without": [{"name": n, "id": v} for n, v in empty],
                "errors": [
                    {"name": n, "id": v, "code": code, "error": e} for n, v, code, e in errs
                ],
            },
            f,
            ensure_ascii=False,
            indent=1,
        )
    print("\nsaved: scan_results.json")


if __name__ == "__main__":
    main()
